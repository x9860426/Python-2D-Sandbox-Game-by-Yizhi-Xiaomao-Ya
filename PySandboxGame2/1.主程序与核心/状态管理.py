import pygame

class 状态管理器:
    """游戏状态管理器，负责管理各种游戏状态"""
    def __init__(self):
        """初始化状态管理器"""
        # 状态字典，存储所有状态
        self.状态 = {
            "无敌": False,  # 是否处于无敌状态
            "无敌时间": 0,  # 剩余无敌时间（秒）
            "最大无敌时间": 30,  # 最大无敌时间（秒）
            "燃烧": False,  # 是否处于燃烧状态
            "燃烧时间": 0,  # 剩余燃烧时间（秒）
            "最大燃烧时间": 10,  # 最大燃烧时间（秒）
            "饥饿": False,  # 是否处于饥饿状态
            "饥饿时间": 0,  # 剩余饥饿时间（秒，-1表示无限）
            "最大饥饿时间": -1  # 最大饥饿时间（秒，-1表示无限）
        }
        
    def 激活无敌状态(self, 持续时间=30):
        """激活无敌状态
        
        参数:
            持续时间: 无敌状态持续的时间（秒）
        """
        self.状态["无敌"] = True
        self.状态["无敌时间"] = 持续时间
        self.状态["最大无敌时间"] = 持续时间
    
    def 关闭无敌状态(self):
        """关闭无敌状态"""
        self.状态["无敌"] = False
        self.状态["无敌时间"] = 0
    
    def 激活燃烧状态(self, 持续时间=10):
        """激活燃烧状态
        
        参数:
            持续时间: 燃烧状态持续的时间（秒）
        """
        self.状态["燃烧"] = True
        self.状态["燃烧时间"] = 持续时间
        self.状态["最大燃烧时间"] = 持续时间
    
    def 关闭燃烧状态(self):
        """关闭燃烧状态"""
        self.状态["燃烧"] = False
        self.状态["燃烧时间"] = 0
    
    def 激活饥饿状态(self, 持续时间=-1):
        """激活饥饿状态
        
        参数:
            持续时间: 饥饿状态持续的时间（秒），-1表示无限时间
        """
        self.状态["饥饿"] = True
        self.状态["饥饿时间"] = 持续时间
        self.状态["最大饥饿时间"] = 持续时间
    
    def 关闭饥饿状态(self):
        """关闭饥饿状态"""
        self.状态["饥饿"] = False
        self.状态["饥饿时间"] = 0
    
    def 更新(self, 时间增量):
        """更新所有状态
        
        参数:
            时间增量: 上次更新到现在的时间间隔（秒）
        """
        # 更新无敌状态
        if self.状态["无敌"]:
            self.状态["无敌时间"] -= 时间增量
            # 检查无敌时间是否结束
            if self.状态["无敌时间"] <= 0:
                self.关闭无敌状态()
        
        # 更新燃烧状态
        if self.状态["燃烧"]:
            self.状态["燃烧时间"] -= 时间增量
            # 检查燃烧时间是否结束
            if self.状态["燃烧时间"] <= 0:
                self.关闭燃烧状态()
        
        # 更新饥饿状态（饥饿状态是无限的，不需要减少时间）
        pass
    
    def 获取无敌状态(self):
        """获取当前无敌状态
        
        返回:
            tuple: (是否无敌, 剩余时间, 最大时间)
        """
        return (
            self.状态["无敌"],
            self.状态["无敌时间"],
            self.状态["最大无敌时间"]
        )
    
    def 是否无敌(self):
        """检查是否处于无敌状态
        
        返回:
            bool: 是否处于无敌状态
        """
        return self.状态["无敌"]
    
    def 获取剩余无敌时间(self):
        """获取剩余无敌时间
        
        返回:
            float: 剩余无敌时间（秒）
        """
        return self.状态["无敌时间"]
    
    def 获取最大无敌时间(self):
        """获取最大无敌时间
        
        返回:
            float: 最大无敌时间（秒）
        """
        return self.状态["最大无敌时间"]
    
    def 获取燃烧状态(self):
        """获取当前燃烧状态
        
        返回:
            tuple: (是否燃烧, 剩余时间, 最大时间)
        """
        return (
            self.状态["燃烧"],
            self.状态["燃烧时间"],
            self.状态["最大燃烧时间"]
        )
    
    def 是否燃烧(self):
        """检查是否处于燃烧状态
        
        返回:
            bool: 是否处于燃烧状态
        """
        return self.状态["燃烧"]
    
    def 获取剩余燃烧时间(self):
        """获取剩余燃烧时间
        
        返回:
            float: 剩余燃烧时间（秒）
        """
        return self.状态["燃烧时间"]
    
    def 获取最大燃烧时间(self):
        """获取最大燃烧时间
        
        返回:
            float: 最大燃烧时间（秒）
        """
        return self.状态["最大燃烧时间"]
    
    def 获取饥饿状态(self):
        """获取当前饥饿状态
        
        返回:
            tuple: (是否饥饿, 剩余时间, 最大时间)
        """
        return (
            self.状态["饥饿"],
            self.状态["饥饿时间"],
            self.状态["最大饥饿时间"]
        )
    
    def 是否饥饿(self):
        """检查是否处于饥饿状态
        
        返回:
            bool: 是否处于饥饿状态
        """
        return self.状态["饥饿"]
    
    def 获取剩余饥饿时间(self):
        """获取剩余饥饿时间
        
        返回:
            float: 剩余饥饿时间（秒）
        """
        return self.状态["饥饿时间"]
    
    def 获取最大饥饿时间(self):
        """获取最大饥饿时间
        
        返回:
            float: 最大饥饿时间（秒）
        """
        return self.状态["最大饥饿时间"]

