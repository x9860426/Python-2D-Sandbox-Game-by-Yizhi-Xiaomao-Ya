# 工具函数：从方块属性同步掉落物配置
def 从方块属性同步掉落物(方块属性):
    """
    从方块属性字典中同步掉落物配置到掉落物管理器
    
    参数:
        方块属性: 包含方块属性的字典
    """
    global 默认掉落物配置
    
    # 清空之前的映射
    方块名称_to_ID.clear()
    ID_to_方块名称.clear()
    
    # 建立名称到ID的映射
    for 方块_id, 属性 in 方块属性.items():
        名称 = 属性.get("名称")
        if 名称:
            方块名称_to_ID[名称] = 方块_id
            ID_to_方块名称[方块_id] = 名称
    
    # 导入物品字典，添加物品名称到ID的映射
    from 物品定义 import 物品 as 物品字典
    for 物品_id, 物品_info in 物品字典.items():
        名称 = 物品_info.get("名称")
        if 名称:
            方块名称_to_ID[名称] = 物品_id
            ID_to_方块名称[物品_id] = 名称
    
    print(f"已建立方块名称映射，包含 {len(方块名称_to_ID)} 个映射关系")
    
    # 初始化默认掉落物配置（使用实际ID）
    默认掉落物配置 = {}
    
    # 将字符串键的配置转换为实际ID的配置
    for 名称, 配置 in 默认掉落物配置_str.items():
        实际方块_id = 方块名称_to_ID.get(名称)
        if 实际方块_id is not None:
            # 深拷贝配置并替换掉落物名称为ID
            新配置 = 配置.copy()
            
            # 替换主掉落物
            掉落物名称 = 新配置.get("掉落物")
            if 掉落物名称 in 方块名称_to_ID:
                新配置["掉落物"] = 方块名称_to_ID[掉落物名称]
            
            # 替换其他掉落选项中的掉落物
            if "其他掉落" in 新配置:
                其他掉落_new = []
                for 选项 in 新配置["其他掉落"]:
                    选项_new = 选项.copy()
                    掉落物名称 = 选项_new.get("掉落物")
                    if 掉落物名称 in 方块名称_to_ID:
                        选项_new["掉落物"] = 方块名称_to_ID[掉落物名称]
                    其他掉落_new.append(选项_new)
                新配置["其他掉落"] = 其他掉落_new
            
            默认掉落物配置[实际方块_id] = 新配置
    
    print(f"已初始化特殊方块掉落配置，共 {len(默认掉落物配置)} 个特殊方块")
    
    # 将默认配置复制到掉落物管理器
    掉落物管理器实例.掉落物配置 = 默认掉落物配置.copy()
    
    # 同步其他方块的掉落配置
    同步数量 = 0
    for 方块_id, 属性 in 方块属性.items():
        # 保留默认配置中的特殊方块规则（包括概率和多掉落选项）
        # 只有当方块不在默认配置中时，才从方块属性同步
        if 方块_id not in 默认掉落物配置:
            # 获取掉落物信息，如果没有则使用方块本身
            掉落物 = 属性.get("掉落物", 方块_id)
            数量 = 属性.get("数量", 1)
            
            # 更新掉落物管理器中的配置
            掉落物管理器实例.设置方块掉落物(方块_id, 掉落物, 数量)
            同步数量 += 1
    
    print(f"已从方块属性同步了 {同步数量} 个方块的掉落物配置，保留了 {len(默认掉落物配置)} 个特殊方块的掉落规则")