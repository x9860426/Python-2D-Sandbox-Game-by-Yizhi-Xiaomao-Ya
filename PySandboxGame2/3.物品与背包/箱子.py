        # === 物品绘制函数 ===
        def 绘制物品(屏幕, x, y, 物品, 格子大小):
            """绘制单个物品，包括图标、数量和耐久度进度条"""
            if 物品 is None:
                return
            
            try:
                # 尝试获取物品图像
                from 图片加载 import 图片管理器
                物品图像 = 图片管理器.获取物品图片(物品.物品_id, (格子大小 - 4, 格子大小 - 4))
                if 物品图像:
                    # 绘制物品图标
                    图标_x = x + 2
                    图标_y = y + 2
                    屏幕.blit(物品图像, (图标_x, 图标_y))
            except Exception as e:
                # 绘制失败时使用默认颜色块
                pygame.draw.rect(屏幕, (200, 100, 100), (x + 2, y + 2, 格子大小 - 4, 格子大小 - 4), 0, 2)
            
            # 绘制物品数量
            if 物品.数量 > 1:
                数量文本 = 小字体.render(str(物品.数量), True, 颜色['文本主色'])
                # 数量文本位置：右下角
                数量_x = x + 格子大小 - 数量文本.get_width() - 2
                数量_y = y + 格子大小 - 数量文本.get_height() - 2
                屏幕.blit(数量文本, (数量_x, 数量_y))
            
            # 绘制耐久度进度条
            max_durability = 物品.获取属性("耐久度", 0)
            if max_durability > 0:
                current_durability = 物品.获取属性("当前耐久度", max_durability)
                durability_percent = (current_durability / max_durability) * 100
                
                # 满95%+不显示耐久进度条
                if durability_percent < 95:
                    # 计算耐久度颜色（从红到绿渐变）
                    if durability_percent <= 50:
                        # 红到黄渐变 (0-50%)
                        ratio = durability_percent / 50
                        red = 255
                        green = int(255 * ratio)
                        blue = 0
                    else:
                        # 黄到绿渐变 (50-100%)
                        ratio = (durability_percent - 50) / 50
                        red = int(255 * (1 - ratio))
                        green = 255
                        blue = 0
                    
                    # 箱子显示3像素高度耐久进度条
                    progress_bar_height = 3
                    progress_bar_width = (格子大小 - 4) * (durability_percent / 100)
                    
                    # 绘制背景条（灰色）
                    pygame.draw.rect(屏幕, (60, 60, 60), 
                                    (x + 2, y + 格子大小 - progress_bar_height - 2, 
                                    格子大小 - 4, progress_bar_height))
                    # 绘制耐久度条（彩色）
                    pygame.draw.rect(屏幕, (red, green, blue), 
                                    (x + 2, y + 格子大小 - progress_bar_height - 2, 
                                    progress_bar_width, progress_bar_height))
        
        # === 槽位绘制函数 ===
        def 绘制格子(x, y, 鼠标悬停=False, 格子类型="normal", 物品=None):
            if 格子类型 == "input":
                格子背景 = (70, 60, 40)
                格子边框 = (160, 140, 100)
            elif 格子类型 == "fuel":
                格子背景 = (70, 40, 40)
                格子边框 = (160, 100, 100)
            elif 格子类型 == "output":
                格子背景 = (40, 70, 50)
                格子边框 = (100, 160, 120)
            else:
                格子背景 = 颜色['格子悬停'] if 鼠标悬停 else 颜色['格子普通']
