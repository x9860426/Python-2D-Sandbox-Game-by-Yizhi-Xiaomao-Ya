    def 查找位置对应的格子(self, 位置, 页面_x, 页面_y, 标题栏高度):
        """查找指定位置的格子
        
        参数:
            位置: (x, y) 鼠标位置
            页面_x, 页面_y: 页面左上角坐标
            标题栏高度: 标题栏高度
            
        返回:
            (类型, 位置) 类型: '箱子'、'背包'、'快捷栏'，位置: (行, 列)
            或者 None 如果位置不在任何格子上
        """
        格子大小 = 44
        格子间距 = 5
        
        # 检查左侧箱子区域
        左侧_x = 页面_x + 20
        左侧_y = 页面_y + 标题栏高度 + 20
        左侧行数 = 5
        左侧列数 = 6
        
        for 行 in range(左侧行数):
            for 列 in range(左侧列数):
                x = 左侧_x + 10 + 列 * (格子大小 + 格子间距)
                y = 左侧_y + 35 + 行 * (格子大小 + 格子间距)
                格子矩形 = pygame.Rect(x, y, 格子大小, 格子大小)
                if 格子矩形.collidepoint(位置):
                    return ('箱子', (行, 列))
        
        # 检查右侧背包区域
        右侧_x = 页面_x + 340
        右侧_y = 页面_y + 标题栏高度 + 20
        右侧行数 = 5
        右侧列数 = 6
        
        for 行 in range(右侧行数):
            for 列 in range(右侧列数):
                x = 右侧_x + 10 + 列 * (格子大小 + 格子间距)
                y = 右侧_y + 35 + 行 * (格子大小 + 格子间距)
                格子矩形 = pygame.Rect(x, y, 格子大小, 格子大小)
                if 格子矩形.collidepoint(位置):
                    return ('背包', (行, 列))
        
        # 检查快捷栏区域
        页面高度 = 450  # 页面高度固定为450
        快捷栏_y = 页面_y + 页面高度 - 70
        快捷栏_x = 页面_x + 20
        
