def 加载物品图片(物品ID, 图片路径=None, 尺寸=None):
    """
    加载指定物品的图片
    
    参数:
        物品ID: 物品的唯一标识符
        图片路径: 可选，图片的完整路径，如果不提供则根据纹理名称自动查找
        尺寸: 可选，图片的目标尺寸，如果不提供则使用默认尺寸
    
    返回:
        pygame.Surface: 加载并缩放后的图片表面
    """
    if 物品ID in 物品图片:
        # 如果图片已经加载过，直接返回缓存的图片
        return 物品图片[物品ID]
    
    try:
        # 获取物品信息
        if 物品ID in 物品:
            物品信息 = 物品[物品ID]
        elif 物品ID in 方块属性:
            物品信息 = 方块属性[物品ID]
        else:
            print(f"警告: 物品ID {物品ID} 不存在于物品或方块属性中")
            return None
        
        # 确定图片文件名
        纹理名称 = 物品信息.get("纹理", None)
        if not 纹理名称:
            print(f"警告: 物品ID {物品ID}({物品信息.get('名称', '未知')}) 没有指定纹理")
            return None
        
        # 如果没有提供图片路径，自动构建路径
        if not 图片路径:
            # 不再在这里处理图片加载路径，完全依赖图片管理器
            # 直接返回None，让图片管理器处理加载逻辑
            
            # 不再在这里尝试加载图片，完全由图片管理器处理
            找到路径 = False
        
        if not 找到路径:
            print(f"警告: 无法找到物品ID {物品ID}({纹理名称}) 的图片")
            # 创建一个简单的颜色方块作为占位符
            占位颜色 = 物品信息.get("颜色", (150, 150, 150))
            图片表面 = pygame.Surface(默认物品图片尺寸, pygame.SRCALPHA)
            图片表面.fill(占位颜色 if len(占位颜色) == 4 else 占位颜色 + (255,))
        
        # 缩放图片到指定尺寸
        if 尺寸:
            图片表面 = pygame.transform.scale(图片表面, 尺寸)
        elif 图片表面.get_size() != 默认物品图片尺寸:
            图片表面 = pygame.transform.scale(图片表面, 默认物品图片尺寸)
        
        # 缓存并返回图片
        物品图片[物品ID] = 图片表面
        return 图片表面
        
    except Exception as e:
        print(f"加载物品ID {物品ID} 图片时出错: {e}")
        return None

